"""Cut the talisman sheet into single charms and write them into the app.

The sheet holds 10 charms on a dark background, 5 per row. Each charm has a thick dark outline
with a soft coloured glow outside it. The cut keeps the outline and everything inside it and drops
the glow (the app draws its own).

Writes  <app>/public/assets/charms/<id>.webp  and  <app>/src/data/charms.gen.ts.
Usage: python -I tools/import_charms.py <sheet.png> <app_dir> [contact.png]
"""
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter
from scipy import ndimage as ndi

# left to right, top to bottom, as on the sheet
CHARMS = [
    ('charm_crane', 'Paper Crane', 'Papierkranich', 'common'),
    ('charm_teacup', 'Teacup', 'Teetasse', 'common'),
    ('charm_cloud', 'Rain Cloud', 'Regenwölkchen', 'common'),
    ('charm_hourglass', 'Hourglass', 'Sanduhr', 'rare'),
    ('charm_compass', 'Compass', 'Kompass', 'rare'),
    ('charm_book', 'Spellbook', 'Zauberbuch', 'rare'),
    ('charm_crystal', 'Crystal', 'Kristall', 'epic'),
    ('charm_jar', 'Firefly Jar', 'Glühwürmchenglas', 'epic'),
    ('charm_moon', 'Crescent Moon', 'Mondsichel', 'mythic'),
    ('charm_planet', 'Mini Planet', 'Mini-Planet', 'mythic'),
]
COLS, ROWS = 5, 2
# darker than this is outline or empty background; the glow right outside each outline is brighter
DARK = 22
MAX_SIDE = 240
PAD = 4


def charm_mask(rgb: np.ndarray) -> np.ndarray:
    """Outline and inside of the one charm in this cell."""
    lum = rgb[..., 0] * 0.299 + rgb[..., 1] * 0.587 + rgb[..., 2] * 0.114
    bright = lum >= DARK
    dark = ~bright
    # empty background: dark areas that reach the cell border
    lab, _ = ndi.label(dark)
    edge = np.unique(np.concatenate([lab[0], lab[-1], lab[:, 0], lab[:, -1]]))
    empty = np.isin(lab, edge[edge > 0])
    # glow: bright areas that touch the empty background
    blab, _ = ndi.label(bright)
    near = ndi.binary_dilation(empty, iterations=2)
    glow_ids = np.unique(blab[near & bright])
    glow = np.isin(blab, glow_ids[glow_ids > 0])
    charm = ~(empty | glow)
    # keep the largest piece, close small gaps
    lab, n = ndi.label(charm)
    if n == 0:
        raise SystemExit('no charm found in a cell')
    sizes = ndi.sum(charm, lab, range(1, n + 1))
    charm = lab == (int(np.argmax(sizes)) + 1)
    return ndi.binary_fill_holes(charm)


def main():
    sheet, app = Path(sys.argv[1]), Path(sys.argv[2])
    contact = Path(sys.argv[3]) if len(sys.argv) > 3 else None
    im = Image.open(sheet).convert('RGB')
    a = np.asarray(im).astype(np.float32)
    H, W = a.shape[:2]
    out_dir = app / 'public' / 'assets' / 'charms'
    out_dir.mkdir(parents=True, exist_ok=True)
    defs, tiles = [], []
    for k, (cid, en, de, rarity) in enumerate(CHARMS):
        r, c = divmod(k, COLS)
        x0, x1 = round(c * W / COLS), round((c + 1) * W / COLS)
        y0, y1 = round(r * H / ROWS), round((r + 1) * H / ROWS)
        cell = a[y0:y1, x0:x1]
        m = charm_mask(cell)
        ys, xs = np.nonzero(m)
        by0, by1 = max(0, ys.min() - PAD), min(m.shape[0], ys.max() + 1 + PAD)
        bx0, bx1 = max(0, xs.min() - PAD), min(m.shape[1], xs.max() + 1 + PAD)
        rgb = cell[by0:by1, bx0:bx1].copy()
        mm = m[by0:by1, bx0:bx1]
        # outside the charm: the outline colour, so the soft edge never shows glow colour
        rgb[~mm] = (12, 10, 16)
        alpha = Image.fromarray((mm * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(0.7))
        tile = Image.fromarray(rgb.clip(0, 255).astype(np.uint8)).convert('RGBA')
        tile.putalpha(alpha)
        s = min(1.0, MAX_SIDE / max(tile.size))
        if s < 1:
            tile = tile.resize((round(tile.width * s), round(tile.height * s)), Image.LANCZOS)
        tile.save(out_dir / f'{cid}.webp', 'WEBP', quality=90, method=6)
        defs.append((cid, en, de, rarity, tile.width, tile.height))
        tiles.append(tile)
        print(f'{cid:16} {tile.width}x{tile.height}')

    lines = [
        '// Generated by tools/import_charms.py from rig_input/talismane_v1.png. Do not edit by hand.',
        "import type { CharmDef } from './types';",
        '',
        'export const CHARMS: CharmDef[] = [',
    ]
    for cid, en, de, rarity, w, h in defs:
        lines.append(f"  {{ id: '{cid}', nameEn: '{en}', nameDe: '{de}', rarity: '{rarity}', w: {w}, h: {h} }},")
    lines += ['];', '']
    (app / 'src' / 'data' / 'charms.gen.ts').write_text('\n'.join(lines), encoding='utf-8')

    if contact:
        cw = MAX_SIDE + 20
        sheet_im = Image.new('RGBA', (cw * COLS * 2, cw * ROWS), (0, 0, 0, 255))
        for k, t in enumerate(tiles):
            r, c = divmod(k, COLS)
            for j, bg in enumerate([(20, 18, 40, 255), (235, 235, 240, 255)]):
                box = Image.new('RGBA', (cw, cw), bg)
                box.alpha_composite(t, ((cw - t.width) // 2, (cw - t.height) // 2))
                sheet_im.paste(box, ((c + j * COLS) * cw, r * cw))
        sheet_im.convert('RGB').save(contact)


if __name__ == '__main__':
    main()
