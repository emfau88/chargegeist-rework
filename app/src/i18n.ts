export type LangCode = 'en' | 'de';

/** The name of a ghost or style in the current language. */
export function nameOf(d: { nameEn: string; nameDe: string }): string {
  return lang() === 'de' ? d.nameDe : d.nameEn;
}
export function quoteOf(d: { quoteEn: string; quoteDe: string }): string {
  return lang() === 'de' ? d.quoteDe : d.quoteEn;
}

export function lang(): LangCode {
  const set = getState().settings.lang;
  if (set !== 'auto') return set;
  return (navigator.language || 'en').toLowerCase().startsWith('de') ? 'de' : 'en';
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s = (lang() === 'de' ? de : en)[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function locale(): string {
  return lang() === 'de' ? 'de-DE' : 'en-GB';
}

export function fmtNum(n: number): string {
  return new Intl.NumberFormat(locale()).format(n);
}

export function fmtDate(ms: number, opts: Intl.DateTimeFormatOptions = { day: 'numeric', month: 'long', year: 'numeric' }): string {
  return new Intl.DateTimeFormat(locale(), opts).format(ms);
}
