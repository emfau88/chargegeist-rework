"""Bring a painted scene (rig_input/szene) into the app.

  far.webp, mid.webp, ground.webp   three layers on one canvas (1024 x 1536), each filled down to the bottom
  props.webp                        a sheet of small things: lanterns, flowers, mushrooms, grass, stones

Writes  app/public/assets/scene/<layer>.webp, app/public/assets/scene/<prop>.webp  and
        app/src/data/scene.gen.ts (canvas, ground line, colours, sizes).

The image agent leaves faint streaks in what should be clear sky. A layer keeps only the land that
reaches its bottom edge, with its own soft rim; everything else goes.

Usage: python -I build_scene.py <rig_input/szene> <app_root> [--sheet <out.png>]
"""
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage as ndi

src, app = Path(sys.argv[1]), Path(sys.argv[2])
SHEET = Path(sys.argv[sys.argv.index("--sheet") + 1]) if "--sheet" in sys.argv else None
OUT = app / "public" / "assets" / "scene"
OUT.mkdir(parents=True, exist_ok=True)

# props on the sheet: name -> a point on it (sheet pixels)
PROPS = {
    "lantern_hang_off": (175, 300), "lantern_hang_on": (560, 300),
    "lantern_stand_off": (945, 250), "lantern_stand_on": (1335, 250),
    # plants for the foreground of the title screen
    "flowers_open": (540, 640), "mushrooms_glow": (1320, 600),
}
# also on the sheet, not in the app (the ground layer has its own flowers, mushrooms and stones):
#   flowers_closed (165, 640), mushrooms_plain (930, 600), grass_a (140, 880), grass_b (400, 870),
#   stone_a (665, 890), stone_b (965, 870), fireflies around (1320, 860)


def land(im):
    """The land of a layer: what is solid and reaches the bottom edge, with its soft rim."""
    a = np.asarray(im.convert("RGBA")).copy()
    solid = a[..., 3] > 128
    lab, n = ndi.label(solid)
    keep = np.unique(lab[-1, :])
    keep = keep[keep > 0]
    main = np.isin(lab, keep)
    main = ndi.binary_fill_holes(main)
    rim = ndi.binary_dilation(main, iterations=3)
    a[..., 3] = np.where(rim, a[..., 3], 0)
    a[a[..., 3] == 0, :3] = 0
    return a, main


info = {"w": 0, "h": 0}
tiles = []
for name in ("far", "mid", "ground"):
    im = Image.open(src / f"{name}.webp")
    a, main = land(im)
    h, w = a.shape[:2]
    info["w"], info["h"] = w, h
    top = np.argmax(main, axis=0)
    bottom = a[-12:, :, :3].reshape(-1, 3).mean(axis=0).round().astype(int).tolist()
    info[name] = dict(top=int(top.min()), mid=int(top[w // 2 - 40 : w // 2 + 40].mean()), bottom="#%02x%02x%02x" % tuple(bottom))
    Image.fromarray(a).save(OUT / f"{name}.webp", "WEBP", quality=90, method=6)
    tiles.append((name, Image.fromarray(a)))

# ---------- props ----------
sheet = np.asarray(Image.open(src / "props.webp").convert("RGBA")).copy()
solid = sheet[..., 3] > 140
lab, n = ndi.label(ndi.binary_closing(solid, iterations=2))
props = {}
for name, (x, y) in PROPS.items():
    i = lab[y, x]
    assert i > 0, (name, "no part at", (x, y))
    mask = ndi.binary_fill_holes(lab == i)
    ys, xs = np.nonzero(mask)
    pad = 4
    y0, y1, x0, x1 = max(0, ys.min() - pad), ys.max() + 1 + pad, max(0, xs.min() - pad), xs.max() + 1 + pad
    crop = sheet[y0:y1, x0:x1].copy()
    near = ndi.binary_dilation(mask, iterations=2)[y0:y1, x0:x1]
    crop[..., 3] = np.where(near, crop[..., 3], 0)
    crop[crop[..., 3] == 0, :3] = 0
    im = Image.fromarray(crop)
    im.save(OUT / f"{name}.webp", "WEBP", quality=92, method=6)
    props[name] = [im.width, im.height]
    tiles.append((name, im))

ts = [
    "// Generated by rig_tools/build_scene.py from rig_input/szene. Do not edit by hand.",
    "/** The painted scene behind the ghost: canvas size, where each layer's land begins (top: highest point, mid: in the middle) and the colour it ends in. */",
    f"export const SCENE = {json.dumps(info, separators=(', ', ': '))} as const;",
    "/** Small things that stand in the scene: width and height in pixels of the scene's canvas. */",
    f"export const SCENE_PROPS: Record<string, [number, number]> = {json.dumps(props, separators=(', ', ': '))};",
    "",
]
(app / "src" / "data" / "scene.gen.ts").write_text("\n".join(ts), encoding="utf-8")
print(json.dumps(info))
print(props)

if SHEET:
    W = 1024 * 3 // 3
    o = Image.new("RGBA", (1024 * 3 // 2 + 40, 1536 // 2 + 420), (150, 160, 205, 255))
    x = 0
    for name, im in tiles[:3]:
        t = im.resize((im.width // 2, im.height // 2), Image.LANCZOS)
        o.alpha_composite(t, (x, 0))
        x += t.width + 10
    x, y = 10, 1536 // 2 + 10
    for name, im in tiles[3:]:
        t = im.copy()
        t.thumbnail((120, 190))
        if x + t.width > o.width - 10:
            x, y = 10, y + 200
        o.alpha_composite(t, (x, y))
        x += t.width + 14
    o.convert("RGB").save(SHEET)
